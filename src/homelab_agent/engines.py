"""Render llama-swap configurations (GPU and CPU engines) from ``models:`` in config.yaml.

Choosing a model = editing ``models.items`` (and the backend ``model:`` names), then running
``homelab-agent render-engines`` (``make engines``) and restarting the engine containers.
"""

from __future__ import annotations

import io
import shlex
from pathlib import Path, PurePosixPath
from typing import Any

from ruamel.yaml import YAML

from homelab_agent.config.models import AppConfig, ModelItem

LLAMA_SERVER = "/app/llama-server"
MODELS_MOUNT = "/models"


def model_args(item: ModelItem, engine_threads: int) -> list[str]:
    path = f"{MODELS_MOUNT}/{PurePosixPath(item.file).name}"
    args = [
        LLAMA_SERVER,
        "--host", "127.0.0.1",
        "--port", "${PORT}",
        "--model", path,
        "--alias", item.name,
        "--ctx-size", str(item.ctx_size),
        "--parallel", str(item.parallel),
        "--jinja",  # chat template with tool-calling support
    ]  # fmt: skip
    if item.engine == "gpu":
        args += ["--n-gpu-layers", str(item.n_gpu_layers)]
    else:
        args += ["--n-gpu-layers", "0"]
    args += ["--threads", str(item.threads or engine_threads)]
    args += ["--flash-attn", "on" if item.flash_attn else "off"]
    if item.cache_type_k:
        args += ["--cache-type-k", item.cache_type_k]
    if item.cache_type_v:
        args += ["--cache-type-v", item.cache_type_v]
    if item.mlock:
        args.append("--mlock")
    args += item.extra_args
    return args


def render_llama_swap(cfg: AppConfig, engine: str) -> str:
    settings = cfg.models.gpu if engine == "gpu" else cfg.models.cpu
    models: dict[str, Any] = {}
    for item in cfg.models.items:
        if item.engine != engine:
            continue
        cmd = " ".join(
            a if a == "${PORT}" else shlex.quote(a)
            for a in model_args(item, settings.default_threads)
        )
        entry: dict[str, Any] = {"cmd": cmd}
        if item.ttl_s:
            entry["ttl"] = item.ttl_s
        models[item.name] = entry
    doc: dict[str, Any] = {
        "healthCheckTimeout": settings.health_timeout_s,
        "logLevel": "info",
        "models": models,
    }
    if not settings.swap and len(models) > 1:
        # keep every model of this engine loaded side by side
        doc["groups"] = {
            f"{engine}-all": {"swap": False, "exclusive": True, "members": list(models)}
        }
    y = YAML()
    y.width = 4096
    buf = io.StringIO()
    buf.write(
        f"# GENERATED by `homelab-agent render-engines` from config.yaml ({engine} engine).\n"
        "# Do not edit: change models.items in config.yaml and re-run `make engines`.\n"
    )
    y.dump(doc, buf)
    return buf.getvalue()


def render_whisper_env(cfg: AppConfig) -> str:
    """Environment of the whisper container (model file, language, threads)."""
    item = next((m for m in cfg.models.items if m.engine == "whisper"), None)
    lines = ["# GENERATED by `homelab-agent render-engines` from config.yaml (whisper engine)."]
    if item is not None:
        lines.append(f"WHISPER_MODEL={PurePosixPath(item.file).name}")
    lines.append(f"WHISPER_LANGUAGE={cfg.voice.language}")
    lines.append(
        f"WHISPER_THREADS={item.threads if item and item.threads else cfg.models.whisper_threads}"
    )
    return "\n".join(lines) + "\n"


def write_engine_configs(cfg: AppConfig, out_dir: str | Path) -> list[Path]:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    written = []
    for engine in ("gpu", "cpu"):
        p = out / f"llama-swap-{engine}.yaml"
        p.write_text(render_llama_swap(cfg, engine), encoding="utf-8")
        written.append(p)
    p = out / "whisper.env"
    p.write_text(render_whisper_env(cfg), encoding="utf-8")
    written.append(p)
    return written


def models_tsv(cfg: AppConfig) -> str:
    """repo<TAB>file<TAB>sha256 lines, consumed by scripts/download-models.sh."""
    return "".join(
        f"{m.repo}\t{m.file}\t{m.sha256 or '-'}\n"
        for m in cfg.models.items
        if m.engine != "whisper" or cfg.voice.enabled  # speech model only when voice is on
    )
